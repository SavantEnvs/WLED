#!/usr/bin/env bash
#
# mayhem/build.sh — host (Linux) build of WLED's firmware sources for fuzzing.
#
# WLED only builds with PlatformIO for ESP8266/ESP32. Here wled00/ is compiled natively as an
# ESP8266 build against a small Arduino/ESP8266 stand-in under mayhem/shim/ (String, Print/Stream,
# WiFiUDP with injectable packets, an in-memory LittleFS, AsyncWebServer/WebSocket request objects,
# no-op GPIO/WiFi). The firmware's own handlers are then driven by the harnesses in mayhem/harness/.
#
# Outputs: /mayhem/fuzz_<name> (libFuzzer), /mayhem/fuzz_<name>-standalone, and
# mayhem/build/wled_selftest (normal flags) which mayhem/test.sh runs.
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

SRC="${SRC:-/mayhem}"
cd "$SRC"
OUT="$SRC/mayhem/build"
mkdir -p "$OUT"

# An ESP8266 build with the features that need real hardware or third-party network stacks off
# (OTA, Alexa, IR, MQTT); everything that parses network/file input stays on.
DEFS=(-DESP8266 -DARDUINO=10819 -DARDUINO_ARCH_ESP8266 -DWLED_HOST_SHIM
      -DWLED_DISABLE_OTA -DWLED_DISABLE_ALEXA -DWLED_DISABLE_INFRARED -DWLED_DISABLE_MQTT
      -DWLED_DISABLE_PARTICLESYSTEM2D
      -Uunix -Ulinux)
INCS=(-I"$SRC/mayhem/shim/include" -I"$SRC/wled00" -I"$SRC/lib/wled_espnow"
      -include "$SRC/mayhem/shim/include/shim_pre.h")
# Upstream targets a 32-bit core where `unsigned long` is 32 bits; brace-init narrowing that is
# fine there is a hard error on LP64, so keep it a warning (no code change).
CXXSTD=(-std=gnu++17 -Wno-c++11-narrowing -w)
# UBSan relaxation (docs/rules/c.md): WLED's colour math shifts negative ints left all over
# (e.g. fastled_slim fill_gradient, run at static init), which is well-defined since C++20 and
# fires before any input is read. Only that check is disabled; the rest of UBSan and ASan halt.
SAN_RELAX="-fno-sanitize=shift-base"

LDEXTRA="-Wl,-T,$SRC/mayhem/shim/dynarray.ld"

SOURCES=()
for f in wled00/*.cpp; do
  case "$f" in
    wled00/wled_server.cpp) continue ;;   # needs html_*.h generated by the npm web-UI build
    wled00/ota_update.cpp) continue ;;    # OTA disabled (flash/partition APIs)
  esac
  SOURCES+=("$f")
done
SOURCES+=(wled00/src/dependencies/e131/ESPAsyncE131.cpp
          wled00/src/dependencies/fastled_slim/fastled_slim.cpp
          wled00/src/dependencies/time/Time.cpp
          wled00/src/dependencies/time/DateStrings.cpp
          wled00/src/dependencies/timezone/Timezone.cpp
          wled00/src/dependencies/network/Network.cpp
          wled00/src/WLEDpixelBus/WLEDpixelBus.cpp
          lib/wled_espnow/wled_espnow.cpp
          mayhem/shim/src/shim.cpp
          mayhem/shim/src/stubs.cpp)

# compile_tree <outdir> <flags...> : compile every source into <outdir>/lib.a
compile_tree() {
  local dir="$1"; shift
  mkdir -p "$dir"
  printf '%s\n' "${SOURCES[@]}" | xargs -P "$MAYHEM_JOBS" -I{} sh -c '
    o="$0/$(echo "{}" | tr / _).o"
    extra=""
    # the usermod registry is a linker-section array of pointers: ASan redzones around its
    # zero-size begin/end markers would break the pointer walk, so leave those globals unpadded.
    case "{}" in */um_manager.cpp) case "$*" in *-fsanitize=*address*) extra="-mllvm -asan-globals=0" ;; esac ;; esac
    exec "$@" $extra -c "{}" -o "$o"' "$dir" "$CXX" "${CXXSTD[@]}" "${DEFS[@]}" "${INCS[@]}" "$@"
  rm -f "$dir/lib.a"
  ar rcs "$dir/lib.a" "$dir"/*.o
}

# 1) the sanitized, coverage-instrumented firmware objects
compile_tree "$OUT/fuzz" $SANITIZER_FLAGS $SAN_RELAX $DEBUG_FLAGS -O1 -fsanitize=fuzzer-no-link

$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/standalone_main.o"
$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.cc -o "$OUT/lsan_off.o"
$CXX "${CXXSTD[@]}" "${DEFS[@]}" "${INCS[@]}" $SANITIZER_FLAGS $SAN_RELAX $DEBUG_FLAGS -O1 -fsanitize=fuzzer-no-link \
  -c mayhem/harness/wled_fuzz_common.cpp -o "$OUT/wled_fuzz_common.o"

# 2) one libFuzzer binary + one standalone reproducer per harness
for h in mayhem/harness/fuzz_*.cpp; do
  name=$(basename "$h" .cpp)
  $CXX "${CXXSTD[@]}" "${DEFS[@]}" "${INCS[@]}" $SANITIZER_FLAGS $SAN_RELAX $DEBUG_FLAGS -O1 -fsanitize=fuzzer-no-link \
    -c "$h" -o "$OUT/$name.o"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OUT/$name.o" "$OUT/wled_fuzz_common.o" \
    "$OUT/lsan_off.o" "$OUT/fuzz/lib.a" $LDEXTRA -o "$SRC/$name"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$OUT/standalone_main.o" "$OUT/$name.o" "$OUT/wled_fuzz_common.o" \
    "$OUT/lsan_off.o" "$OUT/fuzz/lib.a" $LDEXTRA -o "$SRC/$name-standalone"
done

# 3) known-answer self-test of the same firmware code, NORMAL flags (no sanitizers), run by test.sh
compile_tree "$OUT/test" -O1 $COVERAGE_FLAGS
$CXX "${CXXSTD[@]}" "${DEFS[@]}" "${INCS[@]}" -O1 $COVERAGE_FLAGS \
  mayhem/harness/wled_selftest.cpp mayhem/harness/wled_fuzz_common.cpp "$OUT/test/lib.a" $LDEXTRA \
  -o "$OUT/wled_selftest"
